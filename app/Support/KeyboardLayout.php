<?php

namespace App\Support;


class KeyboardLayout
{
    /**
     * Латиница (по физической клавише) => кириллица (та же клавиша на ЙЦУКЕН).
     */
    private const MAP = [
        '`' => 'ё', '~' => 'Ё',

        'q' => 'й', 'w' => 'ц', 'e' => 'у', 'r' => 'к', 't' => 'е',
        'y' => 'н', 'u' => 'г', 'i' => 'ш', 'o' => 'щ', 'p' => 'з',
        '[' => 'х', ']' => 'ъ',
        'Q' => 'Й', 'W' => 'Ц', 'E' => 'У', 'R' => 'К', 'T' => 'Е',
        'Y' => 'Н', 'U' => 'Г', 'I' => 'Ш', 'O' => 'Щ', 'P' => 'З',
        '{' => 'Х', '}' => 'Ъ',

        'a' => 'ф', 's' => 'ы', 'd' => 'в', 'f' => 'а', 'g' => 'п',
        'h' => 'р', 'j' => 'о', 'k' => 'л', 'l' => 'д', ';' => 'ж', "'" => 'э',
        'A' => 'Ф', 'S' => 'Ы', 'D' => 'В', 'F' => 'А', 'G' => 'П',
        'H' => 'Р', 'J' => 'О', 'K' => 'Л', 'L' => 'Д', ':' => 'Ж', '"' => 'Э',

        'z' => 'я', 'x' => 'ч', 'c' => 'с', 'v' => 'м', 'b' => 'и',
        'n' => 'т', 'm' => 'ь', ',' => 'б', '.' => 'ю', '/' => '.',
        'Z' => 'Я', 'X' => 'Ч', 'C' => 'С', 'V' => 'М', 'B' => 'И',
        'N' => 'Т', 'M' => 'Ь', '<' => 'Б', '>' => 'Ю', '?' => ',',
    ];

    /** @var array<string,string>|null кириллица => латиница, строится один раз */
    private static ?array $reverse = null;

    /**
     * Переводит текст в "другую" раскладку посимвольно.
     * Символы, которых нет в карте (пробелы, цифры, уже смешанный текст
     * и т.п.), остаются без изменений.
     */
    public static function swap(string $text): string
    {
        if (self::$reverse === null) {
            self::$reverse = array_flip(self::MAP);
        }

        $result = '';
        $length = mb_strlen($text);

        for ($i = 0; $i < $length; $i++) {
            $char = mb_substr($text, $i, 1);
            $result .= self::MAP[$char] ?? self::$reverse[$char] ?? $char;
        }

        return $result;
    }
}